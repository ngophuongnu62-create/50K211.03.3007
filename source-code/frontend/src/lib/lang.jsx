const LangContext = createContext({ lang: 'vi', setLang: () => {}, t: (s) => s });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem('broadway.lang') || 'vi');
  const value = useMemo(() => ({
    lang,
    setLang: (l) => { localStorage.setItem('broadway.lang', l); setLangState(l); },
    t: (s) => (lang === 'en' && EN[s]) || s,
  }), [lang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

// eslint-disable-next-line react-refresh/only-export-components
export const useLang = () => useContext(LangContext);
